//go:build ignore

// Generate the browser's full-fold exceptions from the exact server dependency.
package main

import (
	"encoding/json"
	"golang.org/x/text/cases"
	"os"
	"strings"
)

func main() {
	fold := cases.Fold()
	special := map[string]string{}
	for r := rune(0); r <= 0x10ffff; r++ {
		if r >= 0xd800 && r <= 0xdfff {
			continue
		}
		s := string(r)
		if v := fold.String(s); v != strings.ToLower(s) {
			special[s] = v
		}
	}
	data, _ := json.Marshal(special)
	source := `/* Generated by scripts/gen-organization-name.go from x/text v0.27.0.
   Unicode data notices: THIRD_PARTY_NOTICES.md M22/G4. */
(function(root){'use strict';const special=` + string(data) + `;
 const normalize=name=>String(name).trim().normalize('NFC');
 const fold=name=>[...normalize(name)].map(c=>special[c]??c.toLowerCase()).join('').normalize('NFC');
 const valid=(name,limit)=>typeof name==='string'&&!/[\p{Cc}\p{Cf}\p{Zl}\p{Zp}]/u.test(name.replaceAll('\u200d',''))&&[...normalize(name)].length>0&&[...normalize(name)].length<=limit;
 const api={normalize,fold,valid};if(typeof module==='object'&&module.exports)module.exports=api;else root.OrganizationName=api;
})(globalThis);
`
	if err := os.WriteFile("web/static/organization-name.js", []byte(source), 0644); err != nil {
		panic(err)
	}
}
